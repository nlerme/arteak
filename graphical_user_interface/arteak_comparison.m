    function list_changed_callback( h_object, event_data )
        % We update current indexes of lists
        g_current_rec_idx = get(g_h_recs_listbox, 'Value');
        g_current_gt_idx  = get(g_h_gt_listbox, 'Value');

        % We check if reconstructed frescoes are the same
        if g_current_rec_idx==g_current_gt_idx
            % If so, we set measurements as empty
            set(g_h_tp_label2, 'string', '');
            set(g_h_fp_label2, 'string', '');
            set(g_h_tn_label2, 'string', '');
            set(g_h_fn_label2, 'string', '');
            set(g_h_ina_label2, 'string', '');
            set(g_h_acc_label2, 'string', '');
            set(g_h_fm_label2, 'string', '');
            set(g_h_te_label2, 'string', '');
            set(g_h_re_label2, 'string', '');
            update_view([], [], [], [], [], [], [], []);
            return;
        end

        % We compare current reconstructed fresco against the current ideal one
        [tp,fp,tn,fn,acc,fm,te,re,ina] = compare_solution_to_gt(g_mydata.frags_sols{g_current_rec_idx}, ...
                                                                         g_mydata.frags_sols{g_current_gt_idx}, ...
                                                                         numel(g_mydata.frags_infos), ...
                                                                         g_translation_tolerance, ...
                                                                         g_rotation_tolerance);

        % We set measurements in respective fields
        set(g_h_tp_label2, 'string', sprintf('%d', numel(tp)));
        set(g_h_fp_label2, 'string', sprintf('%d', numel(fp)));
        set(g_h_tn_label2, 'string', sprintf('%d', numel(tn)));
        set(g_h_fn_label2, 'string', sprintf('%d', numel(fn)));
        set(g_h_ina_label2, 'string', sprintf('%d', numel(ina)));
        set(g_h_acc_label2, 'string', sprintf('%.2f', acc));
        set(g_h_fm_label2, 'string', sprintf('%.2f', fm));
        set(g_h_te_label2, 'string', sprintf('%.2f+/-%.2f', mean(te(2,:)), std(te(2,:))));
        set(g_h_re_label2, 'string', sprintf('%.2f+/-%.2f', mean(re(2,:)), std(re(2,:))));

        % We update the image view
        update_view(tp, fp, tn, fn, te, re, ina, g_mydata.im_recs_color{g_current_rec_idx}, g_mydata.im_recs_alpha{g_current_rec_idx});
    end

    function translation_tolerance_callback( h_object, event_data )
        tt = str2num(get(g_h_tt_edit, 'string'));

        if isempty(tt)
            uiwait(errordlg('Translation tolerance must be a non empty numeric value', 'ARTEAK ERROR', 'modal'));
            return;
        end

        if tt<0.0
            uiwait(errordlg('Translation tolerance must be expressed in pixels and non-negative', 'ARTEAK ERROR', 'modal'));
            return;
        end

        g_translation_tolerance = tt;
        list_changed_callback([], []);
    end

