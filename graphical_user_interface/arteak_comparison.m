    function update_view( tp, fp, tn, fn, te, re, ina, im_rec_color, im_rec_alpha )
        figure(g_fh_cmp);

        if isempty(im_rec_color) || isempty(im_rec_alpha)
            cla(g_axes);
        end

        image(g_axes, im_rec_color, 'AlphaData', im_rec_alpha);
        set(g_axes, 'visible', 'off');
        set(g_axes, 'color', 'none');
        axis image;

        hold on;

        frags_sol     = g_mydata.frags_sols{g_current_rec_idx};
        default_color = g_mydata.colormap(8,:);

        for k=1:length(frags_sol)
            idx         = frags_sol{k}.idx;
            icc         = frags_sol{k}.inner_circle_center;
            icr         = frags_sol{k}.inner_circle_radius;
            translation = frags_sol{k}.translation;
            angle       = frags_sol{k}.angle;
            frag_size   = size(g_mydata.frags_infos{idx}.alpha);

            if isempty(tp) && isempty(fp) && isempty(tn) && isempty(fn) && isempty(ina)
                color = default_color;
            else
                if ~isempty(ina) && sum(ina==idx)==1
                    color = g_inaccurates_color;
                elseif ~isempty(fp) && sum(fp==idx)==1
                    color = g_false_positives_color;
                else
                    color = g_true_positives_color;
                end
            end

            p = apply_forward_transform(icc, translation, angle, frag_size*0.5);

            if g_show_frags_idx
                text(double(p(2)+10), double(p(1)+10), sprintf('%d', idx-1), 'Color', color, 'FontSize', 12);
            end

            if g_show_frags_center
                plot(p(2), p(1), 'r+', 'MarkerSize', 0.5*icr, 'Color', color, 'LineWidth', 2);
            end

            if g_show_frags_neighbors
                numel(frags_sol{k}.neighbors)
                for i=1:numel(frags_sol{k}.neighbors)
                    idx2         = frags_sol{k}.neighbors(i);
                    j            = find(cellfun(@(x) x.idx, frags_sol)==idx2);
                    icc2         = frags_sol{j}.inner_circle_center;
                    translation2 = frags_sol{j}.translation;
                    angle2       = frags_sol{j}.angle;
                    frag_size    = size(g_mydata.frags_infos{idx2}.alpha);
                    p            = apply_forward_transform(icc2, translation, angle, frag_size*0.5);
                    plot([p(2),p(2)], [p(1),p(1)], 'g-', 'LineWidth', 2, 'Color', default_color);
                end
            end
        end

        hold off;

        axtoolbar(g_axes, {'zoomin','zoomout','restoreview','datacursor','pan','export'});
    end

